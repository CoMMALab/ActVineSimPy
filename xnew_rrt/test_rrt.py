class TestFindNearestTo:
 
    def test_finds_closest_of_multiple_nodes(self):
        tree = RRTTree(make_state(0), euclidean_1d_distance, never_goal)
        tree.add_edge(tree.root, make_state(10))
        tree.add_edge(tree.root, make_state(3))
        tree.add_edge(tree.root, make_state(-5))
 
        nearest = tree.find_nearest_to(make_state(4))
        assert nearest.info["state"] == 3
 
