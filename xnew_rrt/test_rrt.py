class TestAddEdge:
 
    def test_adds_child_to_parent(self):
        tree = RRTTree(make_state(0), euclidean_1d_distance, never_goal)
        tree.add_edge(tree.root, make_state(1))
        assert len(tree.root.children) == 1
        assert tree.root.children[0].info["state"] == 1
 
    def test_child_parent_pointer_set(self):
        tree = RRTTree(make_state(0), euclidean_1d_distance, never_goal)
        tree.add_edge(tree.root, make_state(1))
        child = tree.root.children[0]
        assert child.parent is tree.root
 
    def test_non_goal_state_returns_none(self):
        tree = RRTTree(make_state(0), euclidean_1d_distance, never_goal)
        result = tree.add_edge(tree.root, make_state(1))
        assert result is None
 
    def test_goal_state_returns_path(self):
        tree = RRTTree(make_state(0), euclidean_1d_distance, goal_at(5))
        mid = tree.add_edge(tree.root, make_state(3))
        # add_edge doesn't return the created node on non-goal, so grab it
        # from root.children to keep extending the branch
        mid_node = tree.root.children[0]
        path = tree.add_edge(mid_node, make_state(5))
 
        assert path is not None
        assert path[0] is tree.root
        assert path[-1].info["state"] == 5
 
    def test_goal_path_is_start_to_goal_order(self):
        tree = RRTTree(make_state(0), euclidean_1d_distance, goal_at(2))
        tree.add_edge(tree.root, make_state(1))
        n1 = tree.root.children[0]
        path = tree.add_edge(n1, make_state(2))
 
        values = [node.info["state"] for node in path]
        assert values == [0, 1, 2]
 
    def test_multiple_children_supported(self):
        tree = RRTTree(make_state(0), euclidean_1d_distance, never_goal)
        tree.add_edge(tree.root, make_state(1))
        tree.add_edge(tree.root, make_state(2))
        tree.add_edge(tree.root, make_state(3))
        assert len(tree.root.children) == 3
 
 
