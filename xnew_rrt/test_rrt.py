def make_state(value):
    """Convenience factory for a minimal StateInfo with a single numeric
    'value' tucked into `state`, used as a stand-in for real robot state."""
    return StateInfo(
        state=value,
        dstate=0,
        bodies=None,
        moveable_obj_pose=None,
        moveable_obj_dstate=None,
    )
 
 
def euclidean_1d_distance(state_info_a, state_info_b):
    """Trivial distance function: absolute difference of `state` field."""
    return abs(state_info_a["state"] - state_info_b["state"])
 
 
def never_goal(state_info):
    return False
 
 
def goal_at(target_value):
    """Returns a goal_test function that succeeds when state == target_value."""
    def _goal_test(state_info):
        return state_info["state"] == target_value
    return _goal_test
 
 
